-- ==============================================================================
-- SearchForge Baseline Schema Migration (V1)
-- Matches JPA Entities:
--   1. crawled_documents (CrawledDocument)
--   2. indexed_document_metadata (IndexedDocumentMetadata)
--   3. indexed_terms (IndexedTerm)
--   4. term_postings (TermPosting)
--   5. document_embeddings (DocumentEmbeddingEntity)
-- ==============================================================================

CREATE TABLE IF NOT EXISTS crawled_documents (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    url VARCHAR(2048) NOT NULL UNIQUE,
    domain VARCHAR(255) NOT NULL,
    title VARCHAR(512),
    clean_text TEXT,
    content_hash VARCHAR(64) NOT NULL,
    http_status_code INTEGER NOT NULL,
    crawled_at TIMESTAMP WITH TIME ZONE NOT NULL,
    lifecycle_status VARCHAR(32) NOT NULL,
    version INTEGER NOT NULL,
    version_lock BIGINT NOT NULL,
    status_message VARCHAR(1024),
    last_processed_at TIMESTAMP WITH TIME ZONE,
    retry_count INTEGER NOT NULL
);

CREATE INDEX IF NOT EXISTS idx_crawled_docs_domain ON crawled_documents (domain);
CREATE INDEX IF NOT EXISTS idx_crawled_docs_content_hash ON crawled_documents (content_hash);
CREATE INDEX IF NOT EXISTS idx_crawled_docs_status ON crawled_documents (lifecycle_status);

CREATE TABLE IF NOT EXISTS indexed_document_metadata (
    document_id BIGINT NOT NULL PRIMARY KEY,
    token_count INTEGER NOT NULL,
    indexed_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE TABLE IF NOT EXISTS indexed_terms (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term VARCHAR(128) NOT NULL,
    document_frequency INTEGER NOT NULL,
    total_term_frequency BIGINT NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_indexed_terms_term ON indexed_terms (term);

CREATE TABLE IF NOT EXISTS term_postings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    term_id BIGINT NOT NULL,
    document_id BIGINT NOT NULL,
    term_frequency INTEGER NOT NULL,
    positions TEXT NOT NULL,
    CONSTRAINT uk_term_postings_term_doc UNIQUE (term_id, document_id),
    CONSTRAINT fk_term_postings_term FOREIGN KEY (term_id) REFERENCES indexed_terms (id)
);

CREATE INDEX IF NOT EXISTS idx_term_postings_term_id ON term_postings (term_id);
CREATE INDEX IF NOT EXISTS idx_term_postings_doc_id ON term_postings (document_id);

CREATE TABLE IF NOT EXISTS document_embeddings (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    document_id BIGINT NOT NULL UNIQUE,
    model_name VARCHAR(100) NOT NULL,
    dimensions INTEGER NOT NULL,
    vector_data BYTEA NOT NULL,
    content_hash VARCHAR(64),
    document_version INTEGER,
    created_at TIMESTAMP WITH TIME ZONE NOT NULL
);

CREATE UNIQUE INDEX IF NOT EXISTS idx_doc_embeddings_doc_id ON document_embeddings (document_id);
CREATE INDEX IF NOT EXISTS idx_doc_embeddings_model ON document_embeddings (model_name);
